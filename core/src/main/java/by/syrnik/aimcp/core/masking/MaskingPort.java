package by.syrnik.aimcp.core.masking;

/**
 * Маскирование секретов в тексте на агенте-исполнителе до отправки в тех.зону (docs/masking-rules.md).
 * Реализации: регулярные выражения (runner), заглушка для тестов (adapters-stub).
 */
public interface MaskingPort {

    /**
     * Возвращает текст, в котором найденные секреты заменены на {@code [MASKED:<имя правила>]}.
     * Закрыто по умолчанию: если замаскировать не удалось, текст не возвращается.
     *
     * @param text исходный текст, не {@code null}
     * @throws MaskingException маскирование не выполнено (ошибка или бюджет времени исчерпан):
     *                          исходный текст вызывающий наверх не отправляет
     */
    String mask(String text);
}
